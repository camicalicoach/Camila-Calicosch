def say(msg):
    print(msg, flush=True)


def die(msg):
    print('ERROR: ' + msg, file=sys.stderr, flush=True)
    sys.exit(1)


def expand(p):
    return os.path.abspath(os.path.expanduser(p))


def load_config():
    cfg = json.loads(json.dumps(DEFAULT_CONFIG))
    if os.path.exists(CONFIG_PATH):
        with open(CONFIG_PATH, encoding='utf-8') as f:
            user = json.load(f)
        colors = dict(cfg['colors'], **user.get('colors', {}))
        cfg.update(user)
        cfg['colors'] = colors
    return cfg


def read_json(path, default=None):
    if not os.path.exists(path):
        if default is not None:
            return default
        die(f'falta {path}')
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def write_json(path, data):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')


def project_dir(arg):
    p = expand(arg)
    os.makedirs(os.path.join(p, 'work'), exist_ok=True)
    os.makedirs(os.path.join(p, 'assets'), exist_ok=True)
    os.makedirs(os.path.join(p, 'renders'), exist_ok=True)
    return p


def run(cmd, check=True, capture=False, cwd=None, capture_bytes=False):
    """Run a command list. Shows ffmpeg errors in full when it fails."""
    if capture_bytes:
        r = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    else:
        r = subprocess.run(cmd, cwd=cwd, text=True, encoding='utf-8', errors='replace',
                           stdout=subprocess.PIPE if capture else None,
                           stderr=subprocess.PIPE if capture else None)
    if check and r.returncode != 0:
        if capture or capture_bytes:
            err = r.stderr.decode('utf-8', 'replace') if capture_bytes else (r.stdout or '') + (r.stderr or '')
            sys.stderr.write(err)
        die('falló: ' + ' '.join(str(c) for c in cmd[:6]) + ' ...')
    return r


def ffprobe(path):
    r = run(['ffprobe', '-v', 'error', '-print_format', 'json', '-show_format', '-show_streams', path],
            capture=True)
    return json.loads(r.stdout)


def video_info(path):
    """Display size (after rotation), duration, fps, and whether the clip is HDR."""
    d = ffprobe(path)
    v = next((s for s in d['streams'] if s['codec_type'] == 'video'), None)
    a = next((s for s in d['streams'] if s['codec_type'] == 'audio'), None)
    if v is None:
        die(f'{path} no tiene video')
    w, h = int(v['width']), int(v['height'])
    rot = 0
    for sd in v.get('side_data_list', []) or []:
        if 'rotation' in sd:
            rot = int(float(sd['rotation']))
    rot = int(v.get('tags', {}).get('rotate', rot))
    if abs(rot) % 180 == 90:
        w, h = h, w
    num, den = (v.get('avg_frame_rate') or v.get('r_frame_rate') or '30/1').split('/')
    fps = float(num) / float(den) if float(den) else 30.0
    hdr = v.get('color_transfer') in ('arib-std-b67', 'smpte2084')
    return {
        'path': path, 'width': w, 'height': h, 'duration': float(d['format'].get('duration', 0)),
        'fps': round(fps, 3), 'hdr': hdr, 'transfer': v.get('color_transfer', ''),
        'has_audio': a is not None, 'codec': v.get('codec_name', ''),
    }


def os_name():
    s = platform.system().lower()
    return 'macos' if s == 'darwin' else ('windows' if s == 'windows' else 'linux')


def venv_python():
    """The skill's own Python (has faster-whisper + Pillow)."""
    sub = os.path.join('Scripts', 'python.exe') if os_name() == 'windows' else os.path.join('bin', 'python')
    return os.path.join(SKILL_DIR, '.venv', sub)


def npx():
    exe = shutil.which('npx.cmd') if os_name() == 'windows' else None
    return exe or shutil.which('npx') or 'npx'


def hf(args, cwd=None, check=True, capture=False):
    """Run the pinned HyperFrames CLI."""
    return run([npx(), '--yes', f'hyperframes@{HF_VERSION}'] + list(args), cwd=cwd, check=check, capture=capture)


def hdr_lut_path(exposure):
    """Path of the HLG -> SDR Rec.709 3D LUT, built on first use (see make_lut.py)."""
    p = os.path.join(SKILL_DIR, 'assets', 'luts', f'hlg-to-709-e{exposure:.2f}.cube')
    if not os.path.exists(p):
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import make_lut
        make_lut.write_lut(p, exposure)
    return p


def tc(t):
    """Seconds -> m:ss.cc for human-readable lists."""
    m = int(t // 60)
    return f'{m}:{t - 60 * m:05.2f}'
